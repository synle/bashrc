#!/usr/bin/env bash
# Build standalone Android and Fire TV scripts; never execute their ADB payloads.
set -euo pipefail

# Resolve inputs beside this builder so callers can run it from any folder.
source_folder="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
build_folder="$source_folder/build"
mkdir -p "$build_folder"

# Keep temporary output beside artifacts for atomic per-file replacement.
temp_file="$(mktemp "$build_folder/.android-build.XXXXXX")"
trap 'rm -f -- "$temp_file"' EXIT
trap 'exit 1' HUP INT TERM

for platform in android firetv; do
  for action in debloat restore; do
    output_file="$build_folder/${platform}_${action}.sh"
    {
      printf '%s\n' '#!/usr/bin/env bash' '# Generated by docs/android/build.sh. DO NOT EDIT.'
      printf '# Sources: docs/android/%s.sh + docs/android/%s.%s.sh\n\n' "$platform" "$platform" "$action"
      for source_file in "$source_folder/$platform.sh" "$source_folder/$platform.$action.sh"; do
        # awk also separates fragments whose final line has no newline.
        awk 'FNR == 1 && /^#!/ { next } { print }' "$source_file"
        printf '\n'
      done
    } > "$temp_file"
    /bin/bash -n "$temp_file"
    chmod 755 "$temp_file"
    mv -f -- "$temp_file" "$output_file"
    printf 'Built %s\n' "$output_file"
  done
done
