#!/usr/bin/env bash
# Build standalone Android and Fire TV scripts; never execute their ADB payloads.
set -euo pipefail

# Resolve inputs beside this builder so callers can run it from any folder.
source_folder="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
repo_folder="$(cd -- "$source_folder/../.." && pwd)"
build_folder="$source_folder/build"
common_source="$source_folder/common-android.sh"
command mkdir -p "$build_folder"

# Keep temporary output beside artifacts for atomic per-file replacement.
temp_file="$(command mktemp "$build_folder/.android-build.XXXXXX")"
trap 'command rm -f -- "$temp_file"' EXIT
trap 'exit 1' HUP INT TERM

for platform in android-mobile android-tv-fire; do
  for action in debloat restore; do
    output_file="$build_folder/${platform}_${action}.sh"
    {
      printf '%s\n' '#!/usr/bin/env bash' '# Generated by docs/android/build_android.sh. DO NOT EDIT.'
      printf '# Sources: docs/android/common-android.sh + docs/android/%s.sh + docs/android/%s.%s.sh\n\n' "$platform" "$platform" "$action"
      first_source=1
      for source_file in "$common_source" "$source_folder/$platform.sh" "$source_folder/$platform.$action.sh"; do
        # awk also separates fragments whose final line has no newline.
        rel_source_file="${source_file#"$repo_folder"/}"
        if ((first_source == 0)); then
          printf '\n'
        fi
        printf '# --- source_file: %s ---\n' "$rel_source_file"
        command awk 'FNR == 1 && /^#!/ { next } { print }' "$source_file"
        first_source=0
      done
    } > "$temp_file"
    command /bin/bash -n "$temp_file"
    command chmod 755 "$temp_file"
    command mv -f -- "$temp_file" "$output_file"
    printf 'Built %s\n' "$output_file"
  done
done
