/** Reject malformed profile-source nesting through the public refresh helper. */
import fs from "fs";
import os from "os";
import path from "path";
import { spawnSync } from "child_process";
import { afterEach, beforeEach, describe, expect, it } from "vitest";

/** Full source loader used without user startup files. */
const loader = path.resolve("software/bootstrap/safe-source.bash");
/** Canonical refresh implementation. */
const runtime = path.resolve("software/bootstrap/profile-sources.bash");
/** Outer opening marker required by the startup contract. */
const entryBegin = "# BEGIN Sy bash_syle entry point";
/** Outer closing marker required by the startup contract. */
const entryEnd = "# END Sy bash_syle entry point";
/** Inner opening marker required by the startup contract. */
const sourcesBegin = "# BEGIN Sy autogenerated managed profile sources";
/** Inner closing marker required by the startup contract. */
const sourcesEnd = "# END Sy autogenerated managed profile sources";
/** Valid nested baseline for duplicate-marker cases. */
const valid = `${entryBegin}\n:\n${sourcesBegin}\n# Refreshed at epoch: 100000\n${sourcesEnd}\n${entryEnd}\n`;
/** Private home belongs to one test. */
let home;

beforeEach(() => {
  home = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "profile-markers-")));
});
afterEach(() => {
  fs.rmSync(home, { recursive: true, force: true });
});

describe("refresh_profiles marker validation", () => {
  it.each([
    ["duplicate closing marker", valid + sourcesEnd + "\n"],
    ["duplicate opening marker", valid + sourcesBegin + "\n"],
    ["duplicate pair", valid + sourcesBegin + "\n" + sourcesEnd + "\n"],
    ["sibling after entry point", `${entryBegin}\n:\n${entryEnd}\n${sourcesBegin}\n${sourcesEnd}\n`],
    ["sibling before entry point", `${sourcesBegin}\n${sourcesEnd}\n${entryBegin}\n:\n${entryEnd}\n`],
    ["inner block crossing outer end", `${entryBegin}\n${sourcesBegin}\n${entryEnd}\n${sourcesEnd}\n`],
    ["inner block crossing outer start", `${sourcesBegin}\n${entryBegin}\n${sourcesEnd}\n${entryEnd}\n`],
    ["reversed inner markers", `${entryBegin}\n${sourcesEnd}\n${sourcesBegin}\n${entryEnd}\n`],
  ])("rejects %s without modifying startup content or creating refresh files", (_label, before) => {
    const startup = path.join(home, ".bashrc");
    fs.writeFileSync(startup, before);
    const result = spawnSync("/bin/bash", ["--noprofile", "--norc", "-c", '. "$LOADER"; . "$RUNTIME"; refresh_profiles'], {
      env: { ...process.env, HOME: home, BASH_ENV: "", LOADER: loader, RUNTIME: runtime },
      encoding: "utf8",
      timeout: 5000,
    });
    expect(result.status).toBe(1);
    expect(result.stdout).toBe("");
    expect(result.stderr).toBe("[Warning] refresh_profiles found ambiguous managed markers\n");
    expect(fs.readFileSync(startup, "utf8")).toBe(before);
    expect(fs.readdirSync(home)).toMatchInlineSnapshot(`
      [
        ".bashrc",
      ]
    `);
  });
});
