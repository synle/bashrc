/** Exercise cached profile refreshes through the public helper and real filesystem. */
import fs from "fs";
import os from "os";
import path from "path";
import { spawn, spawnSync } from "child_process";
import { afterEach, beforeEach, describe, expect, it } from "vitest";

/** Canonical runtime sources, loaded without user configuration. */
const loader = path.resolve("software/bootstrap/common-functions.bash");
/** Refresh definitions use only Bash and native utilities. */
const runtime = path.resolve("software/bootstrap/profile-sources.bash");
/** Stable marker identity forms part of the user-visible contract. */
const key = "Sy autogenerated managed profile sources";
/** Private home belongs to one test. */
let home;
/** Starting startup content used for unchanged-state assertions. */
let original;

/** Build an isolated startup fixture. @param {string} stamp Cached epoch. @returns {string} Shell source. */
function startup(stamp = "100000") {
  return `# user before\n# BEGIN Sy bash_syle entry point\n:\n# BEGIN ${key}\n# Refreshed at epoch: ${stamp}\n# cached sources\n# END ${key}\n# END Sy bash_syle entry point\n# user after\n`;
}

beforeEach(() => {
  home = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "profile sources ")));
  original = startup();
  fs.mkdirSync(path.join(home, "clock"));
  fs.writeFileSync(path.join(home, "clock/date"), "#!/bin/bash\nprintf '100000\\n'\n", { mode: 0o755 });
  fs.writeFileSync(path.join(home, ".bashrc"), original, { mode: 0o640 });
  fs.writeFileSync(path.join(home, ".bash_syle_common"), "");
  fs.writeFileSync(path.join(home, ".bash_syle"), "");
  fs.writeFileSync(path.join(home, ".bash_syle_cache"), "");
});
afterEach(() => {
  fs.rmSync(home, { recursive: true, force: true });
});

/** Prepare clean Bash with a pinned clock. @param {string} command Public invocation. @returns {object} Spawn arguments and options. */
function invocation(command) {
  return {
    args: ["--noprofile", "--norc", "-c", `. "$LOADER"; . "$RUNTIME"; ${command}`],
    options: {
      env: {
        ...process.env,
        HOME: home,
        PATH: `${home}/clock:${process.env.PATH}`,
        BASH_ENV: "",
        LOADER: loader,
        RUNTIME: runtime,
        BASH_SYLE_COMMON_PATH: path.join(home, ".bash_syle_common"),
        BASH_SYLE_PATH: path.join(home, ".bash_syle"),
        BASH_SYLE_CACHE_PATH: path.join(home, ".bash_syle_cache"),
      },
      encoding: "utf8",
      timeout: 5000,
    },
  };
}

/** Execute real public helpers. @param {string} command Caller shell code. @returns {import("child_process").SpawnSyncReturns<string>} Process result. */
function run(command) {
  const { args, options } = invocation(command);
  return spawnSync("/bin/bash", args, options);
}

/** Schedule an independent shell. @param {string} command Caller shell code. @returns {Promise<object>} Captured process result. */
function runAsync(command) {
  const { args, options } = invocation(command);
  return new Promise((resolve, reject) => {
    const child = spawn("/bin/bash", args, options);
    let stdout = "";
    let stderr = "";
    child.stdout.on("data", (value) => (stdout += value));
    child.stderr.on("data", (value) => (stderr += value));
    child.on("error", reject);
    child.on("close", (status) => resolve({ status, stdout, stderr }));
  });
}

describe("refresh_profiles", () => {
  it("keeps a fresh cached list byte-identical and does not discover new work files", () => {
    fs.writeFileSync(path.join(home, ".work_later.bash"), "printf 'later\\n'\n");
    const result = run("refresh_profiles --if-stale");
    expect(result.status).toBe(0);
    expect(result.stdout).toBe("");
    expect(result.stderr).toBe("");
    expect(fs.readFileSync(path.join(home, ".bashrc"), "utf8")).toBe(original);
    expect(fs.readdirSync(home).filter((name) => name.includes("refresh"))).toMatchInlineSnapshot("[]");
  });

  it.each([
    ["71201", false],
    ["71200", true],
    ["71199", true],
    ["0", true],
    ["100001", true],
    ["invalid", true],
    ["0000071200", true],
    ["999999999999999999999", true],
  ])("handles cached epoch %s at the eight-hour boundary (refresh=%s)", (stamp, refreshed) => {
    fs.writeFileSync(path.join(home, ".bashrc"), startup(stamp));
    fs.writeFileSync(path.join(home, ".work_later.bash"), ":\n");
    const result = run("refresh_profiles --if-stale");
    expect(result.status).toBe(0);
    expect(result.stdout).toBe("");
    expect(result.stderr).toBe("");
    expect(fs.readFileSync(path.join(home, ".bashrc"), "utf8").includes(".work_later.bash")).toBe(refreshed);
  });

  it("forces fresh discovery in core-then-lexical order without executing profiles", () => {
    fs.writeFileSync(path.join(home, ".work_zeta.bash"), "printf 'must not execute\\n'\n");
    fs.writeFileSync(path.join(home, ".work_alpha team.bash"), ":\n");
    fs.writeFileSync(path.join(home, ".work_notes.md"), "not shell");
    fs.writeFileSync(path.join(home, ".bash_syle.bak_latest"), "not shell");
    const result = run("refresh_profiles");
    expect(result.status).toBe(0);
    expect(result.stdout).toBe("");
    expect(result.stderr).toBe("");
    expect(fs.readFileSync(path.join(home, ".bashrc"), "utf8").split(home).join("HOME")).toMatchInlineSnapshot(`
      "# user before
      # BEGIN Sy bash_syle entry point
      :
      # BEGIN Sy autogenerated managed profile sources
      # Refreshed at epoch: 100000
      safe_source 'HOME/.bash_syle_common' || return
      safe_source 'HOME/.bash_syle'
      safe_source 'HOME/.bash_syle_cache'
      safe_source 'HOME/.work_alpha team.bash'
      safe_source 'HOME/.work_zeta.bash'
      refresh_profiles --if-stale
      # END Sy autogenerated managed profile sources
      # END Sy bash_syle entry point
      # user after
      "
    `);
    expect(fs.statSync(path.join(home, ".bashrc")).mode & 0o777).toBe(0o640);
    expect(fs.readdirSync(home).filter((name) => name.includes("refresh"))).toMatchInlineSnapshot("[]");
  });

  it("preserves a user suffix without adding a final newline", () => {
    fs.writeFileSync(path.join(home, ".bashrc"), original.trimEnd());
    const result = run("refresh_profiles");
    expect(result.status).toBe(0);
    expect(result.stderr).toBe("");
    expect(fs.readFileSync(path.join(home, ".bashrc"), "utf8").endsWith("# user after")).toBe(true);
  });

  it("preserves backslashes in home paths while rendering the complete block", () => {
    const renamed = home + "\\test";
    fs.renameSync(home, renamed);
    home = renamed;
    const result = run("refresh_profiles");
    expect(result.status).toBe(0);
    expect(result.stderr).toBe("");
    expect(fs.readFileSync(path.join(home, ".bashrc"), "utf8")).toContain(`safe_source '${home}/.bash_syle_common' || return`);
  });

  it("adds a missing dynamic block inside the retained entry point", () => {
    fs.writeFileSync(
      path.join(home, ".bashrc"),
      "# user before\n# BEGIN Sy bash_syle entry point\n:\n# END Sy bash_syle entry point\n# user after\n",
    );
    const result = run("refresh_profiles --if-stale");
    expect(result.status).toBe(0);
    expect(result.stderr).toBe("");
    const content = fs.readFileSync(path.join(home, ".bashrc"), "utf8");
    expect(content).toContain(`# BEGIN Sy bash_syle entry point\n:\n# BEGIN ${key}\n`);
    expect(content.endsWith(`# END ${key}\n# END Sy bash_syle entry point\n# user after\n`)).toBe(true);
  });

  it("skips protected, cyclic, directory, and control-character work entries", () => {
    fs.writeFileSync(path.join(home, ".work_private.secret.bash"), "not shell");
    fs.symlinkSync(".work_private.secret.bash", path.join(home, ".work_alias.bash"));
    fs.symlinkSync(".work_cycle.bash", path.join(home, ".work_cycle.bash"));
    fs.mkdirSync(path.join(home, ".work_folder.bash"));
    fs.writeFileSync(path.join(home, ".work_\nmarker.bash"), ":\n");
    const result = run("refresh_profiles");
    expect(result.status).toBe(0);
    expect(result.stdout).toBe("");
    expect(result.stderr).toBe("");
    expect(fs.readFileSync(path.join(home, ".bashrc"), "utf8")).not.toContain(".work_");
  });

  it("quotes shell metacharacters without executing them during refresh or later loading", () => {
    fs.writeFileSync(path.join(home, ".work_'$(touch injected).bash"), "printf 'quoted\\n'\n");
    const result = run('refresh_profiles; . "$HOME/.bashrc"');
    expect(result.status).toBe(0);
    expect(result.stdout).toBe("quoted\n");
    expect(result.stderr).toBe("");
    expect(fs.existsSync(path.join(home, "injected"))).toBe(false);
  });

  it("does not replace invalid user syntax or advance its timestamp", () => {
    const before = original + "if then\n";
    fs.writeFileSync(path.join(home, ".bashrc"), before);
    const result = run("refresh_profiles");
    expect(result.status).toBe(1);
    expect(result.stdout).toBe("");
    expect(result.stderr).toBe("[Warning] refresh_profiles generated invalid startup syntax\n");
    expect(fs.readFileSync(path.join(home, ".bashrc"), "utf8")).toBe(before);
    expect(fs.readdirSync(home).filter((name) => name.includes("refresh"))).toMatchInlineSnapshot("[]");
  });

  it("refuses a startup symlink to a protected target before reading its contents", () => {
    fs.renameSync(path.join(home, ".bashrc"), path.join(home, "private.secret.bash"));
    fs.symlinkSync("private.secret.bash", path.join(home, ".bashrc"));
    const result = run("refresh_profiles");
    expect(result.status).toBe(1);
    expect(result.stdout).toBe("");
    expect(result.stderr).toBe("[Warning] refresh_profiles cannot resolve an eligible startup file\n");
    expect(fs.readdirSync(home).filter((name) => name.includes("refresh"))).toMatchInlineSnapshot("[]");
    expect(fs.lstatSync(path.join(home, ".bashrc")).isSymbolicLink()).toBe(true);
  });

  it("preserves eligible startup symlinks while replacing their canonical file", () => {
    fs.renameSync(path.join(home, ".bashrc"), path.join(home, "actual.bash"));
    fs.symlinkSync("actual.bash", path.join(home, ".bashrc"));
    const result = run("refresh_profiles");
    expect(result.status).toBe(0);
    expect(result.stderr).toBe("");
    expect(fs.lstatSync(path.join(home, ".bashrc")).isSymbolicLink()).toBe(true);
    expect(fs.readFileSync(path.join(home, "actual.bash"), "utf8")).toContain("# Refreshed at epoch: 100000\n");
  });

  it("skips a busy automatic refresh and reports a busy manual refresh without removing its lock", () => {
    fs.writeFileSync(path.join(home, ".bashrc"), startup("0"));
    fs.mkdirSync(path.join(home, ".bashrc.profile-refresh.lock"));
    const automatic = run("refresh_profiles --if-stale");
    expect(automatic.status).toBe(0);
    expect(automatic.stderr).toBe("");
    const manual = run("refresh_profiles");
    expect(manual.status).toBe(1);
    expect(manual.stderr).toBe("[Warning] refresh_profiles cannot acquire the refresh lock\n");
    expect(fs.statSync(path.join(home, ".bashrc.profile-refresh.lock")).isDirectory()).toBe(true);
    expect(fs.readFileSync(path.join(home, ".bashrc"), "utf8")).toBe(startup("0"));
  });

  it("preserves unrelated edits made while a candidate is being built", () => {
    fs.mkdirSync(path.join(home, "bin"));
    fs.writeFileSync(
      path.join(home, "bin/cp"),
      '#!/bin/bash\n/bin/cp "$@" || exit\nif [ ! -f "$HOME/edited" ]; then printf "# concurrent edit\\n" >> "$HOME/.bashrc"; printf done > "$HOME/edited"; fi\n',
      { mode: 0o755 },
    );
    const result = run('PATH="$HOME/bin:$PATH"; refresh_profiles');
    expect(result.status).toBe(1);
    expect(result.stdout).toBe("");
    expect(result.stderr).toBe("[Warning] refresh_profiles startup file changed; retry is safe\n");
    expect(fs.readFileSync(path.join(home, ".bashrc"), "utf8")).toBe(original + "# concurrent edit\n");
    expect(fs.readdirSync(home).filter((name) => name.includes("refresh"))).toMatchInlineSnapshot("[]");
  });

  it("serializes concurrent stale refreshes without duplicate blocks or leftover locks", async () => {
    fs.writeFileSync(path.join(home, ".bashrc"), startup("0"));
    fs.writeFileSync(path.join(home, ".work_later.bash"), ":\n");
    const results = await Promise.all([runAsync("refresh_profiles --if-stale"), runAsync("refresh_profiles --if-stale")]);
    expect(results).toMatchInlineSnapshot(`
      [
        {
          "status": 0,
          "stderr": "",
          "stdout": "",
        },
        {
          "status": 0,
          "stderr": "",
          "stdout": "",
        },
      ]
    `);
    const content = fs.readFileSync(path.join(home, ".bashrc"), "utf8");
    expect(content.match(/^# BEGIN Sy autogenerated managed profile sources$/gm)).toMatchInlineSnapshot(`
      [
        "# BEGIN Sy autogenerated managed profile sources",
      ]
    `);
    expect(content).toContain(".work_later.bash");
    expect(fs.readdirSync(home).filter((name) => name.includes("refresh"))).toMatchInlineSnapshot("[]");
  });

  it("prints inline help without needing a startup file", () => {
    fs.unlinkSync(path.join(home, ".bashrc"));
    const result = run("refresh_profiles --help");
    expect(result.status).toBe(0);
    expect(result.stdout).toContain("refresh_profiles: refresh the cached startup-source list.");
    expect(result.stderr).toBe("");
  });

  it.each(["unexpected", "--if-stale extra"])("rejects invalid arguments %s without effects", (args) => {
    const result = run(`refresh_profiles ${args}`);
    expect(result.status).toBe(2);
    expect(result.stdout).toBe("");
    expect(result.stderr).toBe("[Warning] refresh_profiles expects [--if-stale]\n");
    expect(fs.readFileSync(path.join(home, ".bashrc"), "utf8")).toBe(original);
  });
});
