import { describe, it, expect } from "vitest";

import fs from "fs";

import path from "path";

import vm from "vm";

import { getIndexFunction, expandSourceMarkers } from "./setup.js";

const clone = getIndexFunction("clone");

const vsCodeRaw = fs.readFileSync("software/scripts/advanced/vs-code.js", "utf-8");

const vsCodeSource = expandSourceMarkers(vsCodeRaw);

function loadVsCode(overrides = {}) {
  const sandbox = {
    is_os_mac: false,
    is_os_windows: false,
    // Defaults to the custom-theme path (GUI present, no opt-out) so settings assertions
    // below see the per-theme customizations. Override is_gui to exercise the fallback.
    is_gui: 1,
    parseBoolean: (v) => String(v ?? "").toLowerCase() === "true" || Number.parseInt(v, 10) === 1,
    getRuntimeOption: (_key, parser) => (parser ? parser("") : ""),
    clone,
    // llm-common.js (SOURCEd in) derives the LLM home from LLM_ROOT_FOLDER.
    process: { env: { HOME: "/mock/home", LLM_ROOT_FOLDER: "/mock/home/sy/ai_llm" } },
    fs: { existsSync: () => false },
    path: { join: (...args) => args.join("/"), resolve: (p) => p },
    findPath: () => null,
    log: () => {},
    getWindowAppDataRoamingUserPath: () => null,
    getOsxApplicationSupportCodeUserPath: () => "/mock/home/Library/Application Support",
    BASE_HOMEDIR_LINUX: "/mock/home",
    SY_ROOT_FOLDER: "/mock/home/sy",
    EDITOR_CONFIGS: {
      fontFamily: "FiraCode",
      fontFamilyDefaultFallback: "monospace",
      fontSize: 14,
      fontSizeDefaultFallback: 13,
      fontWeightNumber: 400,
      tabSize: 2,
      maxLineSize: 120,
      terminalScrollback: 200000,
      ignoredFiles: [],
      ignoredFolders: [],
    },
    list: (strings) =>
      strings
        .join("")
        .split("\n")
        .map((s) => s.trim())
        .filter((s) => s && !s.startsWith("//")),
    getAutoGeneratedText: () => "auto-generated\n",
    BUILD_DIR: ".build",
    backupConfigFile: async () => {},
    writeJson: async () => {},
    readJson: async () => ({}),
    writeBuildArtifact: async () => {},
    ...overrides,
  };
  vm.runInNewContext(vsCodeSource.replace(/^(const|let) /gm, "var "), sandbox);
  return sandbox;
}

function makeProvider(host) {
  const isLocal = host === "127.0.0.1";
  return {
    id: isLocal ? "ollama-local" : "ollama-my-desktop",
    baseURL: `http://${host}:11434/v1`,
  };
}

describe("_buildChatLanguageModels", () => {
  it("uses the provider id as the entry name (matches opencode + Zed naming)", () => {
    const vs = loadVsCode();
    const result = vs._buildChatLanguageModels([makeProvider("127.0.0.1"), makeProvider("192.0.2.45")]);
    expect(result.map((e) => e.name)).toEqual(["ollama-local", "ollama-my-desktop"]);
  });

  it("strips the /v1 suffix from baseURL so Copilot Chat hits the native /api root", () => {
    const vs = loadVsCode();
    const result = vs._buildChatLanguageModels([makeProvider("192.0.2.45")]);
    expect(result[0].url).toBe("http://192.0.2.45:11434");
  });

  it("hardcodes vendor to 'ollama' on every entry", () => {
    const vs = loadVsCode();
    const result = vs._buildChatLanguageModels([makeProvider("127.0.0.1"), makeProvider("192.0.2.45")]);
    expect(result.every((e) => e.vendor === "ollama")).toBe(true);
  });

  it("drops existing vendor:'ollama' rows and re-derives them from discovery (we own the ollama subset)", () => {
    const vs = loadVsCode();
    const existing = [{ name: "Ollama", vendor: "ollama", url: "http://stale.example:11434" }];
    const result = vs._buildChatLanguageModels([makeProvider("127.0.0.1")], existing);
    expect(result).toEqual([{ name: "ollama-local", vendor: "ollama", url: "http://127.0.0.1:11434" }]);
  });

  it("preserves non-ollama vendors (UI-added providers like anthropic / openai survive a re-run)", () => {
    const vs = loadVsCode();
    const existing = [
      { name: "Claude", vendor: "anthropic", url: "https://api.anthropic.com" },
      { name: "Ollama", vendor: "ollama", url: "http://stale.example:11434" },
    ];
    const result = vs._buildChatLanguageModels([makeProvider("127.0.0.1")], existing);
    expect(result).toEqual([
      { name: "Claude", vendor: "anthropic", url: "https://api.anthropic.com" },
      { name: "ollama-local", vendor: "ollama", url: "http://127.0.0.1:11434" },
    ]);
  });

  it("returns only passthrough entries when no providers were discovered (clears stale ollama rows)", () => {
    const vs = loadVsCode();
    const existing = [
      { name: "Claude", vendor: "anthropic", url: "https://api.anthropic.com" },
      { name: "Ollama", vendor: "ollama", url: "http://stale.example:11434" },
    ];
    const result = vs._buildChatLanguageModels([], existing);
    expect(result).toEqual([{ name: "Claude", vendor: "anthropic", url: "https://api.anthropic.com" }]);
  });

  it("returns an empty array when neither providers nor existing entries are present", () => {
    const vs = loadVsCode();
    expect(vs._buildChatLanguageModels([])).toEqual([]);
  });
});
