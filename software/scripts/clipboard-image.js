/** Installs ~/.local/bin/save_clipboard_image, which saves the clipboard image to a png and prints its path. */

/**
 * Writes the `save_clipboard_image` executable onto PATH.
 *
 * Standalone on purpose (no profile sourcing): its main caller is vim's
 * `system()` inside an editor launched by an AI CLI (Ctrl+G), which runs a bare
 * shell with a stripped environment.
 *
 * Images default to the clipboard folder under SY_ROOT_FOLDER.
 * A non-empty CLIPBOARD_IMAGE_FOLDER overrides that destination.
 * The deployment-rendered root supports stripped editor environments.
 *
 * Side effects: installs the image saver and independent retention executable.
 *
 * @returns {Promise<void>}
 */
async function doWork() {
  /** @type {string} Existing executable used by Vim. */
  const binPath = path.join(BASE_HOMEDIR_LINUX, ".local", "bin", "save_clipboard_image");
  /** @type {string} Separate retention executable; never called from copy/paste. */
  const cleanupPath = path.join(path.dirname(binPath), "syle_clipboard_cleanup");
  /** @type {string} Canonical root retained when Vim strips environment variables. */
  const quotedRoot = "'" + SY_ROOT_FOLDER.replace(/'/g, "'\\''") + "'";

  log(">> Updating clipboard image saver", binPath);

  if (!IS_DRY_RUN) {
    fs.mkdirSync(path.dirname(binPath), { recursive: true });
  }

  await writeText(
    binPath,
    code`
      #!/usr/bin/env bash
      # save_clipboard_image: save the image on the system clipboard to a png file.
      # Prints the saved path on stdout (nothing else); errors go to stderr.
      # Exit 0 = saved, 1 = clipboard has no image, 2 = no supported clipboard tool.
      # Generated by software/scripts/clipboard-image.js - edit that file, not this one.

      if [ "$1" = "-h" ] || [ "$1" = "--help" ] || [ "$1" = "help" ]; then
        printf '%s\\n' "save_clipboard_image: save clipboard image to a png, print its path
        save_clipboard_image             -> <SY_ROOT_FOLDER>/.syle_clipboard/clipboard_<timestamp>.png
        save_clipboard_image <out.png>   -> given path
        CLIPBOARD_IMAGE_FOLDER overrides the default folder when non-empty.
        exit 0 saved | 1 no image on clipboard | 2 no supported clipboard tool"
        exit 0
      fi

      # --- Save folder ---
      function _pick_save_folder() {
        local root=${quotedRoot}
        [ -z "$SY_ROOT_FOLDER" ] || root="$SY_ROOT_FOLDER"
        local folder="$root/.syle_clipboard"
        [ -z "$CLIPBOARD_IMAGE_FOLDER" ] || folder="$CLIPBOARD_IMAGE_FOLDER"
        mkdir -p "$folder" || return
        printf '%s\\n' "$folder"
      }

      out_file="$1"
      if [ -z "$out_file" ]; then
        folder="$(_pick_save_folder)" || exit 2
        out_file="$folder/clipboard_$(date +%Y%m%d_%H%M%S)_$$_$RANDOM.png"
      else
        mkdir -p "$(dirname "$out_file")"
      fi

      # --- Windows clipboard via PowerShell (WSL + MinGW) ---
      # -STA is required: the WinForms clipboard API fails in a multithreaded apartment.
      function _save_with_powershell() {
        "$1" -NoProfile -STA -Command "
          Add-Type -AssemblyName System.Windows.Forms, System.Drawing
          \\$img = [System.Windows.Forms.Clipboard]::GetImage()
          if (\\$img -eq \\$null) { exit 1 }
          \\$img.Save('$2', [System.Drawing.Imaging.ImageFormat]::Png)
        " < /dev/null > /dev/null 2>&1
      }

      # --- macOS clipboard via AppleScript (no pngpaste install needed) ---
      # Passed with -e, never stdin: the script holds «» chars, and osascript decodes a
      # stdin script with the session text encoding, which a stripped env (vim launched
      # from an AI CLI) lacks -> misparse -> false "no image". -e args are always UTF-8.
      function _save_with_osascript() {
        osascript \\
          -e 'on run argv' \\
          -e 'set outPath to item 1 of argv' \\
          -e 'try' \\
          -e 'set pngData to (the clipboard as «class PNGf»)' \\
          -e 'on error' \\
          -e 'error number 1' \\
          -e 'end try' \\
          -e 'set fileRef to open for access (POSIX file outPath) with write permission' \\
          -e 'set eof of fileRef to 0' \\
          -e 'write pngData to fileRef' \\
          -e 'close access fileRef' \\
          -e 'end run' \\
          "$1" < /dev/null > /dev/null 2>&1
      }

      os_name="$(uname -s)"
      status=2

      if [ "$os_name" = "Darwin" ]; then
        if type -P pngpaste > /dev/null 2>&1; then
          pngpaste "$out_file" > /dev/null 2>&1 && status=0 || status=1
        elif type -P osascript > /dev/null 2>&1; then
          _save_with_osascript "$out_file" && status=0 || status=1
        fi
      elif grep -qi microsoft /proc/version 2> /dev/null && type -P powershell.exe > /dev/null 2>&1; then
        # WSL: PowerShell runs on Windows, so hand it a Windows path.
        _save_with_powershell powershell.exe "$(wslpath -w "$out_file")" && status=0 || status=1
      elif case "$os_name" in MINGW* | MSYS* | CYGWIN*) true ;; *) false ;; esac; then
         _save_with_powershell powershell "$(cygpath -w "$out_file" 2> /dev/null || printf '%s\\n' "$out_file")" && status=0 || status=1
      elif [ -n "$TERMUX_VERSION" ]; then
        printf '%s\\n' "save_clipboard_image: Android clipboard is text-only in Termux" >&2
        exit 2
      elif [ -n "$WAYLAND_DISPLAY" ] && type -P wl-paste > /dev/null 2>&1; then
        if wl-paste --list-types 2> /dev/null | grep -q '^image/png$'; then
          wl-paste --type image/png > "$out_file" 2> /dev/null && status=0 || status=1
        else
          status=1
        fi
      elif [ -n "$DISPLAY" ] && type -P xclip > /dev/null 2>&1; then
        if xclip -selection clipboard -t TARGETS -o 2> /dev/null | grep -q '^image/png$'; then
          xclip -selection clipboard -t image/png -o > "$out_file" 2> /dev/null && status=0 || status=1
        else
          status=1
        fi
      fi

      if [ "$status" -eq 2 ]; then
        printf '%s\\n' "save_clipboard_image: no supported clipboard tool (need pngpaste/osascript, powershell, wl-paste, or xclip)" >&2
        exit 2
      fi

      # Never leave an empty or partial file behind when there was no image.
      if [ "$status" -ne 0 ] || [ ! -s "$out_file" ]; then
        rm -f "$out_file"
        printf '%s\\n' "save_clipboard_image: clipboard has no image" >&2
        exit 1
      fi

      printf '%s\\n' "$out_file"
    `,
  );

  /** @type {string} Standalone Node source with its deployment root rendered once. */
  const cleanupSource = (await readText`software/scripts/clipboard-cleanup.common.cjs`).replace(
    '"__SY_CLIPBOARD_ROOT__"',
    JSON.stringify(SY_ROOT_FOLDER),
  );
  await writeText(cleanupPath, cleanupSource);

  if (!IS_DRY_RUN) {
    fs.chmodSync(binPath, 0o755);
    fs.chmodSync(cleanupPath, 0o755);
  }
}

/** Removes both managed clipboard executables without deleting saved content. */
async function undoWork() {
  for (const name of ["save_clipboard_image", "syle_clipboard_cleanup"]) {
    /** @type {string} Managed executable being uninstalled. */
    const binPath = path.join(BASE_HOMEDIR_LINUX, ".local", "bin", name);
    if (!IS_DRY_RUN && fs.existsSync(binPath)) fs.unlinkSync(binPath);
  }
}
